public class Rectangle{
    private double length;
    private double breadth;

    public double getLength()
    {
        return length;
    }
    public void setLength(double newlength)
    {
        length = newlength;
    }
    public double getBreadth()
    {
        return breadth;
    }
    public void setBreadth(double newbreadth)
    {
        breadth = newbreadth;
    }
}
